USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA WILDFIRE.PIPELINE;
ALTER SESSION SET USE_CACHED_RESULT = FALSE;

SELECT 'GLM' AS tbl, COUNT(*) AS row_count FROM GLM
UNION ALL SELECT 'NEW_FIRES', COUNT(*) FROM NEW_FIRES;

CREATE OR REPLACE TABLE GLM_PTS AS
SELECT TRY_TO_TIMESTAMP_NTZ(FLASH_TIME::VARCHAR) AS flash_ts,
       LAT, LON,
       ST_MAKEPOINT(LON, LAT) AS geog
FROM GLM;

CREATE OR REPLACE TABLE FIRE_PTS AS
SELECT ROW_NUMBER() OVER (ORDER BY "TIME", LATITUDE, LONGITUDE) AS fire_id,
       TRY_TO_TIMESTAMP_NTZ("TIME"::VARCHAR) AS fire_ts,
       LATITUDE, LONGITUDE,
       ST_MAKEPOINT(LONGITUDE, LATITUDE) AS geog
FROM NEW_FIRES;

SELECT (SELECT COUNT(*) FROM GLM_PTS  WHERE flash_ts IS NULL) AS bad_flash_times,
       (SELECT COUNT(*) FROM FIRE_PTS WHERE fire_ts  IS NULL) AS bad_fire_times;

SELECT f.fire_id,
       f.fire_ts,
       COUNT(*) AS n_flashes,
       ROUND(MIN(ST_DISTANCE(f.geog, g.geog)) / 1000, 2) AS nearest_km
FROM FIRE_PTS f
JOIN GLM_PTS g
  ON ST_DWITHIN(f.geog, g.geog, 5000)
 AND g.flash_ts BETWEEN DATEADD(hour, -48, f.fire_ts) AND f.fire_ts
GROUP BY f.fire_id, f.fire_ts
ORDER BY f.fire_id;

SELECT COUNT(*) AS n_flashes
FROM FIRE_PTS f
JOIN GLM_PTS g
  ON ST_DWITHIN(f.geog, g.geog, 5000)
 AND g.flash_ts BETWEEN DATEADD(hour, -48, f.fire_ts) AND f.fire_ts
WHERE f.fire_id = 42;

SELECT start_time,
       LEFT(query_text, 60) AS query,
       total_elapsed_time   AS total_ms,
       execution_time       AS exec_ms,
       rows_produced
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY())
WHERE query_text ILIKE '%ST_DWITHIN%'
  AND query_text NOT ILIKE '%QUERY_HISTORY%'
ORDER BY start_time DESC
LIMIT 10;